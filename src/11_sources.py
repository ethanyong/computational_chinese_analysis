"""Step 11 — Whose voice? Named-source citations on the China desk (exploratory).

Motivation: the open-vocabulary comparison (step 8) surfaced China-desk-specific changes in
source words (fewer 中央社 / 明报 / 记者, more 通报 / 官网).  This step measures that directly.
Because the hypothesis was generated by looking at the same data, results here are labelled
EXPLORATORY: they are hypotheses for future, pre-registered tests, not confirmations.

Source groups (substring match on simplified-Chinese text; only unambiguous organisation names):
  prc_state     PRC state / Party media
  prc_other     other mainland outlets (commercial or semi-official)
  prc_official  official channels: 官网 (official website), 通报 (official bulletin/notice)
  taiwan        Taiwan media
  hongkong      Hong Kong media
  intl          international wires and media
Ambiguous strings were dropped (e.g. 中时 also occurs inside ordinary words, 求是 inside 实事求是).

Measures, for the China desk and (for comparison) the World desk:
  * citations per 10,000 CJK characters, yearly, Poisson QMLE 95% CI;
  * composition: share of each group among all named media citations (excludes prc_official),
    yearly, bootstrap 95% CI over articles.
  * Interrupted time series on yearly shares (n = 13 years): share ~ year + post(Dec 2021).
  * Official channels: China-vs-World difference-in-differences at Dec 2021 with placebo breaks,
    and three robustness checks — articles that mention COVID excluded; the pandemic years
    2020-22 excluded; and year-level inference (Welch test on yearly log rate ratios).
Corpus: realtime full text (unselected).  Print-desk leads are reported in the CSV as a check.

Context that matters for interpretation: Apple Daily (closed 24 Jun 2021) and Stand News
(closed 29 Dec 2021) ceased publishing; fewer citations of Hong Kong media after 2021 can reflect
the disappearance of outlets, not only editorial choice.
"""
import numpy as np
import pandas as pd
import statsmodels.api as sm
import statsmodels.formula.api as smf
import matplotlib.pyplot as plt
from scipy import stats

from config import INTERIM, RESULTS, SEED, RESTRUCTURE_DATE
from plotstyle import INK2, events, save

GROUPS = {
    "prc_state": ["新华社", "新华网", "中新社", "中国新闻社", "中新网", "人民日报", "人民网", "央视", "中央电视台",
                  "环球时报", "环球网", "光明日报", "解放军报", "中国日报", "经济日报", "中国青年报", "法制日报"],
    "prc_other": ["财新", "澎湃", "第一财经", "南方周末", "南方都市报", "新京报", "北京青年报", "界面新闻",
                  "长安街知事", "21世纪经济报道", "每日经济新闻", "红星新闻", "观察者网"],
    "prc_official": ["官网", "通报"],
    "taiwan": ["中央社", "自由时报", "联合报", "中国时报", "联合新闻网", "东森", "三立", "ETtoday", "风传媒", "苹果新闻网"],
    "hongkong": ["明报", "星岛", "东方日报", "苹果日报", "香港01", "端传媒", "立场新闻", "南华早报", "信报", "大公报", "文汇报",
                 "有线新闻", "香港电台"],
    "intl": ["路透社", "法新社", "美联社", "彭博社", "共同社", "韩联社", "塔斯社", "美国之音", "自由亚洲电台", "BBC",
             "英国广播公司", "纽约时报", "华尔街日报", "金融时报", "华盛顿邮报", "日经", "CNN", "德国之声"],
}
MEDIA = ["prc_state", "prc_other", "taiwan", "hongkong", "intl"]
# articles that mention the pandemic or its control measures (robustness check only)
COVID_TERMS = ["疫情", "新冠", "冠病", "核酸", "防疫", "封控", "隔离", "清零", "病例"]
GROUP_COLOR = {"prc_state": "#e34948", "prc_other": "#e87ba4", "prc_official": "#4a3aa7",
               "taiwan": "#1baf7a", "hongkong": "#eda100", "intl": "#2a78d6"}
GROUP_LABEL = {"prc_state": "PRC state media", "prc_other": "Other mainland media", "prc_official": "Official channels (官網 official website, 通報 official bulletin)",
               "taiwan": "Taiwan media", "hongkong": "Hong Kong media", "intl": "International wires/media"}
RNG = np.random.default_rng(SEED)


def count(text):
    return {g: sum(text.count(t) for t in ts) for g, ts in GROUPS.items()}


def main():
    art = pd.read_parquet(f"{INTERIM}/articles.parquet")
    art = art[((art.corpus == "realtime") & art.fulltext_ok) | ((art.corpus == "print") & (art.pub_year >= 2016))].copy()
    # print desks: leads only (first two paragraphs), the unselected text unit
    art["unit"] = np.where(art.corpus == "print", art.text.str.split("\n").str[:2].str.join("\n"), art.text)
    art["n_chars"] = art.unit.str.count(r"[一-鿿]")
    c = pd.DataFrame(art.unit.map(count).tolist(), index=art.index)
    art = pd.concat([art, c], axis=1)
    art["media_total"] = art[MEDIA].sum(axis=1)
    art["post"] = (art.pub_date >= pd.Timestamp(RESTRUCTURE_DATE)).astype(int)

    rates, shares = [], []
    for (corpus, desk, yr), g in art[art.desk.isin(["china", "world"])].groupby(["corpus", "desk", "pub_year"]):
        for grp in GROUPS:
            if g[grp].sum() == 0:
                rates.append(dict(corpus=corpus, desk=desk, year=yr, group=grp, rate=0.0, lo=0.0, hi=np.nan))
                continue
            m = sm.GLM(g[grp], np.ones((len(g), 1)), family=sm.families.Poisson(), offset=np.log(g.n_chars.clip(lower=1))).fit(cov_type="HC1")
            b, se = m.params.iloc[0], m.bse.iloc[0]
            rates.append(dict(corpus=corpus, desk=desk, year=yr, group=grp, rate=np.exp(b) * 1e4,
                              lo=np.exp(b - 1.96 * se) * 1e4, hi=np.exp(b + 1.96 * se) * 1e4))
        M = g[MEDIA].values
        tot = M.sum()
        if tot == 0:
            continue
        boot = []
        for _ in range(1000):
            i = RNG.integers(0, len(g), len(g))
            boot.append(M[i].sum(0) / max(M[i].sum(), 1))
        boot = np.array(boot)
        for j, grp in enumerate(MEDIA):
            shares.append(dict(corpus=corpus, desk=desk, year=yr, group=grp, share=M[:, j].sum() / tot,
                               lo=np.percentile(boot[:, j], 2.5), hi=np.percentile(boot[:, j], 97.5), n_citations=int(tot)))
    rates, shares = pd.DataFrame(rates), pd.DataFrame(shares)
    rates.to_csv(f"{RESULTS}/sources_rates.csv", index=False)
    shares.to_csv(f"{RESULTS}/sources_shares.csv", index=False)

    its = []
    for corpus in ["realtime", "print"]:
        for grp in MEDIA:
            s = shares[(shares.corpus == corpus) & (shares.desk == "china") & (shares.group == grp)].copy()
            s["t"], s["post"] = s.year - 2021.9, (s.year >= 2022).astype(int)
            if len(s) < 6:
                continue
            m = smf.ols("share ~ t + post", s).fit(cov_type="HC1")
            pre, post = s[s.post == 0].share.mean(), s[s.post == 1].share.mean()
            its.append(dict(corpus=corpus, group=grp, pre_mean=pre, post_mean=post, trend=m.params["t"],
                            level_shift=m.params["post"], lo=m.conf_int().loc["post", 0], hi=m.conf_int().loc["post", 1],
                            p=m.pvalues["post"], n_years=len(s)))
    its = pd.DataFrame(its)
    its.to_csv(f"{RESULTS}/sources_its.csv", index=False)

    # Official-channel references: China vs World difference-in-differences (year FE), with
    # placebo breaks on 1 Dec of every year, as for the markers in step 6
    rt = art[(art.corpus == "realtime") & art.desk.isin(["china", "world"]) & (art.n_chars > 0)].copy()
    did = []
    for by in range(2014, 2025):
        rt["cp"] = ((rt.desk == "china") & (rt.pub_date >= pd.Timestamp(f"{by}-12-01"))).astype(int)
        m = smf.glm("prc_official ~ C(desk) + C(pub_year) + cp", rt, family=sm.families.Poisson(),
                    offset=np.log(rt.n_chars)).fit(cov_type="HC1")
        b, se = m.params["cp"], m.bse["cp"]
        did.append(dict(break_year=by, irr=np.exp(b), lo=np.exp(b - 1.96 * se), hi=np.exp(b + 1.96 * se), p=m.pvalues["cp"]))
    did = pd.DataFrame(did)
    did.to_csv(f"{RESULTS}/sources_official_did_placebo.csv", index=False)
    print("\nOfficial-channel references, China vs World DiD by break year:\n", did.round(3).to_string())

    # Robustness of the Dec 2021 official-channel DiD to the obvious alternative explanations
    def did_at(d, label):
        d = d.copy()
        d["cp"] = ((d.desk == "china") & (d.pub_date >= pd.Timestamp(RESTRUCTURE_DATE))).astype(int)
        m = smf.glm("prc_official ~ C(desk) + C(pub_year) + cp", d, family=sm.families.Poisson(),
                    offset=np.log(d.n_chars)).fit(cov_type="HC1")
        b, se = m.params["cp"], m.bse["cp"]
        return dict(spec=label, n=len(d), irr=np.exp(b), lo=np.exp(b - 1.96 * se), hi=np.exp(b + 1.96 * se), p=m.pvalues["cp"])
    covid = rt.unit.str.contains("|".join(COVID_TERMS))
    rob = [did_at(rt, "all articles (main estimate)"),
           did_at(rt[~covid], "excluding articles that mention COVID"),
           did_at(rt[~rt.pub_year.isin([2020, 2021, 2022])], "excluding 2020-2022 (2013-19 vs 2023-25)")]
    # year-level inference: Welch test of yearly log(China rate / World rate), 2022-25 vs 2013-21
    yr_rates = rates[(rates.corpus == "realtime") & (rates.group == "prc_official")].pivot(index="year", columns="desk", values="rate")
    lr = np.log(yr_rates.china / yr_rates.world).replace([np.inf, -np.inf], np.nan).dropna()
    pre_y, post_y = lr[lr.index <= 2021], lr[lr.index >= 2022]
    tt = stats.ttest_ind(post_y, pre_y, equal_var=False)
    se = np.sqrt(post_y.var(ddof=1) / len(post_y) + pre_y.var(ddof=1) / len(pre_y))
    diff, crit = post_y.mean() - pre_y.mean(), stats.t.ppf(.975, tt.df)
    rob.append(dict(spec="year level: Welch test on yearly log rate ratios", n=len(lr), irr=np.exp(diff),
                    lo=np.exp(diff - crit * se), hi=np.exp(diff + crit * se), p=tt.pvalue))
    rob = pd.DataFrame(rob)
    rob["covid_share_china_post"] = covid[(rt.desk == "china") & (rt.pub_date >= pd.Timestamp(RESTRUCTURE_DATE))].mean()
    rob.to_csv(f"{RESULTS}/sources_official_robustness.csv", index=False)
    print("\nOfficial-channel DiD robustness:\n", rob.round(3).to_string())

    # Keyword-in-context sample so a reader can see what the measure counts
    rng = np.random.default_rng(SEED)
    lines = ["# What do 通报 and 官网 refer to on the China desk? (random contexts, realtime)\n"]
    for era, mask in [("2013-Nov 2021", art.post == 0), ("Dec 2021-2025", art.post == 1)]:
        sub = art[(art.corpus == "realtime") & (art.desk == "china") & mask & (art.prc_official > 0)]
        ctx = []
        for t in sub.unit:
            for term in ["通报", "官网"]:
                i = t.find(term)
                while i >= 0:
                    ctx.append(t[max(0, i - 25):i + 15].replace("\n", " "))
                    i = t.find(term, i + 1)
        pick = rng.choice(len(ctx), min(25, len(ctx)), replace=False) if ctx else []
        lines.append(f"\n## {era} ({len(ctx)} occurrences in {len(sub)} articles)\n")
        lines += [f"- ...{ctx[k]}..." for k in pick]
    open(f"{RESULTS}/sources_official_kwic.md", "w", encoding="utf-8").write("\n".join(lines))

    pd.set_option("display.width", 220)
    print("China desk, realtime: citations per 10k chars\n",
          rates[(rates.corpus == "realtime") & (rates.desk == "china")].pivot(index="year", columns="group", values="rate").round(2).to_string())
    print("\nWorld desk, realtime: citations per 10k chars\n",
          rates[(rates.corpus == "realtime") & (rates.desk == "world")].pivot(index="year", columns="group", values="rate").round(2).to_string())
    print("\nChina desk, realtime: share of named media citations\n",
          shares[(shares.corpus == "realtime") & (shares.desk == "china")].pivot(index="year", columns="group", values="share").round(3).to_string())
    print("\nChina desk, print leads: share of named media citations\n",
          shares[(shares.corpus == "print") & (shares.desk == "china")].pivot(index="year", columns="group", values="share").round(3).to_string())
    print("\nInterrupted time series on yearly China-desk shares:\n", its.round(3).to_string())

    fig, axes = plt.subplots(1, 2, figsize=(14, 4.2))
    ax = axes[0]
    s = shares[(shares.corpus == "realtime") & (shares.desk == "china")]
    for grp in MEDIA:
        g = s[s.group == grp]
        ax.plot(g.year, g.share * 100, color=GROUP_COLOR[grp], marker="o", lw=1.6, label=GROUP_LABEL[grp])
        ax.fill_between(g.year, g.lo * 100, g.hi * 100, color=GROUP_COLOR[grp], alpha=.12, lw=0)
    ax.set_ylim(0, None)
    ax.set_ylabel("% of named media citations")
    ax.set_title("China desk (realtime): who is cited, as a share of named media", fontsize=10)
    ax.legend(fontsize=7.5, loc="upper left", ncol=2)
    events(ax, label=False)
    ax = axes[1]
    r = rates[(rates.corpus == "realtime") & (rates.desk == "china") & (rates.group == "prc_official")]
    rw = rates[(rates.corpus == "realtime") & (rates.desk == "world") & (rates.group == "prc_official")]
    ax.plot(r.year, r.rate, color=GROUP_COLOR["prc_official"], marker="o", lw=1.6, label="China desk")
    ax.fill_between(r.year, r.lo, r.hi, color=GROUP_COLOR["prc_official"], alpha=.12, lw=0)
    ax.plot(rw.year, rw.rate, color=INK2, marker="s", lw=1.2, label="World desk")
    ax.set_ylim(0, None)
    ax.set_ylabel("per 10,000 characters")
    ax.set_title("Official-channel references: 官網 (official website), 通報 (official bulletin)", fontsize=10)
    ax.legend(fontsize=8)
    events(ax, label=False)
    fig.suptitle("Figure 10 (exploratory). Named sources on the China desk, realtime corpus (95% CI). "
                 "Hong Kong outlets Apple Daily and Stand News closed in 2021.", x=.01, ha="left")
    save(fig, "fig10_sources")


if __name__ == "__main__":
    main()
